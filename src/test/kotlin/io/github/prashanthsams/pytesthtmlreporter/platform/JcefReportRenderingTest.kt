package io.github.prashanthsams.pytesthtmlreporter.platform

import com.intellij.openapi.diagnostic.logger
import com.intellij.testFramework.PlatformTestUtil
import io.github.prashanthsams.pytesthtmlreporter.core.MiniJson
import io.github.prashanthsams.pytesthtmlreporter.core.TestData
import io.github.prashanthsams.pytesthtmlreporter.viewer.JcefReportBrowser
import io.github.prashanthsams.pytesthtmlreporter.viewer.JcefSupport
import org.cef.CefSettings
import org.cef.browser.CefBrowser
import org.cef.handler.CefDisplayHandlerAdapter
import java.nio.file.Files
import java.nio.file.Path
import java.util.concurrent.LinkedBlockingQueue
import java.util.concurrent.atomic.AtomicInteger

/**
 * Loads a report generated by pytest-html-reporter 0.4.3 into the production [JcefReportBrowser] (off-screen, so it
 * runs headless) and checks what the page itself can see: its scripts ran, relative screenshot files resolve from
 * disk with no server, files outside the report folder are refused, a reload keeps the current report page, and the
 * dashboard scrolls rather than being squeezed in a short tool window.
 * Returns early when the test runtime has no JCEF.
 */
class JcefReportRenderingTest : ReporterTestCase() {

    private lateinit var directory: Path
    private val loads = AtomicInteger()
    private val failures = LinkedBlockingQueue<String>()
    private val results = LinkedBlockingQueue<String>()

    override fun setUp() {
        super.setUp()
        directory = Files.createTempDirectory("render dir ü")
    }

    override fun tearDown() {
        try {
            directory.toFile().deleteRecursively()
        } finally {
            super.tearDown()
        }
    }

    fun testRendersARealReportOfflineAndKeepsThePageOnReload() {
        if (!JcefSupport.isSupported()) {
            LOG.warn("JCEF is not available in this test runtime; skipping")
            return
        }
        val report = TestData.copyReport("0.4.3", directory.resolve("out dir ü"), "my report ü.html")
        val screenshot = Files.list(report.resolveSibling("pytest_screenshots")).use { it.findFirst().get().fileName.toString() }
        // A real PNG just outside the report folder: the viewer must not load it.
        Files.copy(report.resolveSibling("pytest_screenshots").resolve(screenshot), directory.resolve("outside.png"))

        val view = createView()
        view.load(report)
        PlatformTestUtil.waitWithEventsDispatching({ "report did not load: $failures" }, { loads.get() >= 1 }, TIMEOUT_SECONDS)
        assertTrue(failures.toString(), failures.isEmpty())

        val page = evaluate(view, inspection(screenshot))
        println("Rendered report as seen by the page: $page")
        assertEquals("Pytest HTML Reporter", page.stringValue("title"))
        assertEquals("the screenshot beside the report loads from disk", 4L, page["inside"])
        assertEquals("a file outside the report folder is refused", -1L, page["outside"])
        assertTrue("the report's charts were drawn by its own scripts", (page["canvases"] as Long) > 0)
        assertTrue("the report's tables were initialised by its own scripts", page["jquery"] == true)
        assertTrue(page.stringValue("theme") in setOf("light", "dark"))

        // Move to another report page, reload from disk, and expect to land on the same page.
        view.jbCefBrowser.cefBrowser.executeJavaScript("window.location.hash = '#test-metrics';", "", 0)
        PlatformTestUtil.waitWithEventsDispatching("hash change not observed", { view.currentUrl?.contains("#test-metrics") == true }, TIMEOUT_SECONDS)
        val before = loads.get()
        view.reload()
        PlatformTestUtil.waitWithEventsDispatching("reload did not finish", { loads.get() > before }, TIMEOUT_SECONDS)
        val reloaded = evaluate(view, "console.log('$MARKER' + JSON.stringify({hash: window.location.hash}));")
        println("After reload: $reloaded")
        assertTrue(reloaded.stringValue("hash"), reloaded.stringValue("hash")!!.startsWith("#test-metrics"))
    }

    fun testDashboardScrollsInAShortToolWindowInsteadOfBeingSqueezed() {
        if (!JcefSupport.isSupported()) {
            LOG.warn("JCEF is not available in this test runtime; skipping")
            return
        }
        val report = TestData.copyReport("0.4.3", directory.resolve("out"))
        val view = createView()
        // The size of a tool window docked at the bottom: as wide as the IDE, a couple of hundred pixels high.
        val cefBrowser = view.jbCefBrowser.cefBrowser
        cefBrowser.uiComponent.setSize(1320, 230)
        cefBrowser.wasResized(1320, 230)
        view.load(report)
        PlatformTestUtil.waitWithEventsDispatching({ "report did not load: $failures" }, { loads.get() >= 1 }, TIMEOUT_SECONDS)

        val dashboard = evaluate(view, DASHBOARD_INSPECTION)
        println("Dashboard in a short viewer: $dashboard")
        assertTrue("the report is laid out for a wide, short window: $dashboard",
            dashboard.longValue("width") >= 1200 && dashboard.longValue("height") <= 300)
        assertTrue("the dashboard is taller than the window, so it scrolls: $dashboard",
            dashboard.longValue("dashboard") > dashboard.longValue("height"))
        assertTrue("the test count does not run into the outcome counters: $dashboard", dashboard.longValue("countGap") >= 0)
        assertTrue("the highlight caption is inside its card: $dashboard", dashboard.longValue("captionRoom") >= 0)

        // With a previous build the report adds a "since last build" highlight, and the dashboard is given more room.
        val withPreviousBuild = evaluate(view, "document.querySelector('.delta-highlight').classList.remove('is-empty');\n$DASHBOARD_INSPECTION")
        println("Dashboard in a short viewer, with a previous build: $withPreviousBuild")
        assertTrue("the dashboard grows for the second highlight: $withPreviousBuild",
            withPreviousBuild.longValue("dashboard") > dashboard.longValue("dashboard"))
        assertTrue("the second highlight's caption is inside its card: $withPreviousBuild", withPreviousBuild.longValue("captionRoom") >= 0)
    }

    private fun createView(): JcefReportBrowser {
        val view = JcefReportBrowser(project, testRootDisposable, object : JcefReportBrowser.Listener {
            override fun loadStarted() = Unit
            override fun loadFinished() {
                loads.incrementAndGet()
            }
            override fun loadFailed(errorText: String, url: String) {
                failures += "$errorText $url"
            }
        }, headless = true)
        view.jbCefBrowser.jbCefClient.addDisplayHandler(object : CefDisplayHandlerAdapter() {
            override fun onConsoleMessage(browser: CefBrowser?, level: CefSettings.LogSeverity?, message: String?, source: String?, line: Int): Boolean {
                if (message != null && message.startsWith(MARKER)) results += message.removePrefix(MARKER)
                return false
            }
        }, view.jbCefBrowser.cefBrowser)
        return view
    }

    private fun evaluate(view: JcefReportBrowser, script: String): Map<*, *> {
        results.clear()
        view.jbCefBrowser.cefBrowser.executeJavaScript(script, "", 0)
        PlatformTestUtil.waitWithEventsDispatching("the page did not answer", { results.isNotEmpty() }, TIMEOUT_SECONDS)
        return MiniJson.parse(results.poll()) as Map<*, *>
    }

    private fun Map<*, *>.stringValue(key: String) = this[key] as? String

    private fun Map<*, *>.longValue(key: String) = this[key] as Long

    private fun inspection(screenshot: String) = """
        (function () {
          var result = {
            title: document.title,
            theme: document.documentElement.getAttribute('data-theme'),
            canvases: document.querySelectorAll('canvas').length,
            jquery: typeof window.jQuery === 'function' && typeof window.jQuery.fn.DataTable === 'function'
          };
          var pending = 2;
          function settle() { if (--pending === 0) { console.log('$MARKER' + JSON.stringify(result)); } }
          function probe(key, src) {
            var image = new Image();
            image.onload = function () { result[key] = image.naturalWidth; settle(); };
            image.onerror = function () { result[key] = -1; settle(); };
            image.src = src;
          }
          probe('inside', 'pytest_screenshots/$screenshot');
          probe('outside', '../outside.png');
        })();
    """.trimIndent()

    private companion object {
        private val LOG = logger<JcefReportRenderingTest>()
        private const val MARKER = "PHR-TEST:"
        private const val TIMEOUT_SECONDS = 60

        /**
         * Measures the dashboard once the report has opened it and it has outgrown the window, or after 10 s if that
         * never happens. Until the report opens a tab, all of them are on the page.
         */
        private val DASHBOARD_INSPECTION = """
            (function () {
              var started = Date.now();
              var box = function (selector) { return document.querySelector(selector).getBoundingClientRect(); };
              (function inspect() {
                var settled = document.body.getAttribute('data-tab') === 'dashboard' && box('.dashboard-viewport').height > window.innerHeight;
                if (!settled && Date.now() - started < 10000) { setTimeout(inspect, 50); return; }
                var cards = document.querySelectorAll('#dashboard .row.rowcard > .card');
                var highlights = cards[cards.length - 1];
                var captions = Array.prototype.filter.call(highlights.querySelectorAll('.suite-highlights-header'),
                  function (caption) { return caption.offsetParent !== null; });
                var caption = captions[captions.length - 1].getBoundingClientRect();
                console.log('$MARKER' + JSON.stringify({
                  width: window.innerWidth,
                  height: window.innerHeight,
                  dashboard: Math.round(box('.dashboard-viewport').height),
                  countGap: Math.round(box('#dashboard .card__footer').top - box('#dashboard .total_count__label').bottom),
                  captionRoom: Math.round(highlights.getBoundingClientRect().bottom - caption.bottom)
                }));
              })();
            })();
        """.trimIndent()
    }
}
