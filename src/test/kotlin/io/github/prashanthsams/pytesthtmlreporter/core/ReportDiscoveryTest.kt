package io.github.prashanthsams.pytesthtmlreporter.core

import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.attribute.FileTime
import java.util.concurrent.TimeUnit

/** Recognition, bounded discovery and run-to-report matching, on reports generated by the real reporter. */
class ReportDiscoveryTest {

    @get:Rule
    val temporary = TemporaryFolder()

    private fun project(): Path = temporary.newFolder("project dir ü").toPath()

    @Test
    fun `recognises reports from every supported release`() {
        for (version in listOf("0.4.3", "0.3.0")) {
            val report = TestData.report(version).resolve(ReportPaths.DEFAULT_FILE_NAME)
            assertTrue(version, ReportFiles.isReport(report))
            assertTrue(version, ReportFiles.isComplete(report))
        }
    }

    @Test
    fun `rejects unrelated and partially written html`() {
        val root = project()
        val unrelated = Files.writeString(root.resolve("index.html"), "<html><head><title>Docs</title></head></html>")
        assertFalse(ReportFiles.isReport(unrelated))

        val source = Files.readAllBytes(TestData.report("0.4.3").resolve(ReportPaths.DEFAULT_FILE_NAME))
        val partial = Files.write(root.resolve("partial.html"), source.copyOf(source.size / 2))
        assertTrue("the head is already there", ReportFiles.isReport(partial))
        assertFalse("but the page is not finished", ReportFiles.isComplete(partial))
    }

    @Test
    fun `finds default and custom-named reports, newest first`() {
        val root = project()
        val older = TestData.copyReport("0.3.0", root.resolve("report"))
        val custom = TestData.copyReport("0.4.3", root.resolve("out dir ü"), "my report ü.html")
        Files.setLastModifiedTime(older, FileTime.fromMillis(System.currentTimeMillis() - 60_000))

        val result = ReportScanner().scan(listOf(root), ReportScanner.DEFAULT_EXCLUDED_NAMES)
        assertEquals(listOf(custom, older), result.reports.map { it.file })
        assertTrue(result.reports.all { it.hasOutputJson })
        assertFalse(result.truncated)
    }

    @Test
    fun `skips environments, dependencies and build output`() {
        val root = project()
        TestData.copyReport("0.4.3", root.resolve(".venv/lib/report"))
        TestData.copyReport("0.4.3", root.resolve("custom-env/report")).also { Files.writeString(root.resolve("custom-env/pyvenv.cfg"), "home = /usr\n") }
        TestData.copyReport("0.4.3", root.resolve("conda-env/report")).also { Files.createDirectories(root.resolve("conda-env/conda-meta")) }
        TestData.copyReport("0.4.3", root.resolve("node_modules/pkg"))
        TestData.copyReport("0.4.3", root.resolve("build/reports"))
        TestData.copyReport("0.4.3", root.resolve("pkg.egg-info"))
        val kept = TestData.copyReport("0.4.3", root.resolve("reports"))

        val result = ReportScanner().scan(listOf(root), ReportScanner.DEFAULT_EXCLUDED_NAMES)
        assertEquals(listOf(kept), result.reports.map { it.file })
    }

    @Test
    fun `does not follow symbolic links`() {
        val root = project()
        val outside = temporary.newFolder("outside").toPath()
        TestData.copyReport("0.4.3", outside.resolve("report"))
        try {
            Files.createSymbolicLink(root.resolve("linked"), outside)
        } catch (e: Exception) {
            assumeTrue("symbolic links unavailable: ${e.message}", false)
        }
        assertTrue(ReportScanner().scan(listOf(root), emptySet()).reports.isEmpty())
    }

    @Test
    fun `stays within the depth and directory limits`() {
        val root = project()
        TestData.copyReport("0.4.3", root.resolve("a/b/c/d"))
        assertTrue(ReportScanner(ReportScanner.Limits(maxDepth = 2)).scan(listOf(root), emptySet()).reports.isEmpty())
        assertEquals(1, ReportScanner(ReportScanner.Limits(maxDepth = 4)).scan(listOf(root), emptySet()).reports.size)

        val limited = ReportScanner(ReportScanner.Limits(maxDirectories = 2)).scan(listOf(root), emptySet())
        assertTrue(limited.truncated)
        assertEquals(2, limited.visitedDirectories)
    }

    @Test
    fun `matches a run only to a report written after it started`() {
        val root = project()
        val report = TestData.copyReport("0.4.3", root.resolve("report"))
        val startedAt = System.currentTimeMillis()
        Files.setLastModifiedTime(report, FileTime.fromMillis(startedAt - TimeUnit.MINUTES.toMillis(5)))
        assertNull("a stale report is never presented as this run's", ReportLocator.find(ExpectedReport.Exact(report), startedAt))

        Files.setLastModifiedTime(report, FileTime.fromMillis(startedAt + 1_000))
        assertEquals(report, ReportLocator.find(ExpectedReport.Exact(report), startedAt)?.file)
        assertNull(ReportLocator.find(ExpectedReport.Exact(root.resolve("missing.html")), startedAt))
    }

    @Test
    fun `finds the newest report matching a placeholder path`() {
        val root = project()
        val startedAt = System.currentTimeMillis() - 10_000
        val earlier = TestData.copyReport("0.4.3", root.resolve("reports/20260306"), "run.html")
        val latest = TestData.copyReport("0.4.3", root.resolve("reports/20260307"), "run.html")
        Files.setLastModifiedTime(earlier, FileTime.fromMillis(startedAt + 1_000))
        Files.setLastModifiedTime(latest, FileTime.fromMillis(startedAt + 2_000))
        val expected = ExpectedReport.Matching(
            root.resolve("reports"), ReportPaths.patternFor("reports/%Y%m%d/run.html", root, emptyMap()), maxDepth = 4,
        )
        assertEquals(latest, ReportLocator.find(expected, startedAt)?.file)
    }

    @Test
    fun `waits for a report to be completely written`() = runBlocking {
        val root = project()
        val source = Files.readAllBytes(TestData.report("0.4.3").resolve(ReportPaths.DEFAULT_FILE_NAME))
        val file = Files.write(root.resolve("pytest_html_report.html"), source.copyOf(1000))
        assertFalse(ReportLocator.awaitComplete(file, timeoutMillis = 600, pollMillis = 100))
        Files.write(file, source)
        assertTrue(ReportLocator.awaitComplete(file, timeoutMillis = 3_000, pollMillis = 100))
    }

    @Test
    fun `inspects a single known folder without recursion`() {
        val root = project()
        TestData.copyReport("0.4.3", root.resolve("report"))
        TestData.copyReport("0.4.3", root.resolve("report/nested"))
        assertEquals(1, ReportScanner().inspectDirectory(root.resolve("report")).size)
        assertNotNull(ReportFiles.candidate(root.resolve("report/pytest_html_report.html")))
    }
}
